"""
Prompt Model for default and AI-generated writing prompts.
"""

from datetime import datetime, timezone
from typing import Optional, TYPE_CHECKING
from sqlalchemy import Integer, String, Text, Boolean, DateTime, ForeignKey
from sqlalchemy.orm import Mapped, mapped_column, relationship
from src.db.base import Base

if TYPE_CHECKING:
    from src.models.category import Category


class Prompt(Base):
    """
    Represents a writing prompt, either pre-seeded or dynamically generated by Gemini AI.
    """
    __tablename__ = "prompts"

    id: Mapped[int] = mapped_column(primary_key=True, autoincrement=True)
    category_id: Mapped[int] = mapped_column(ForeignKey("categories.id", ondelete="CASCADE"), nullable=False, index=True)
    content: Mapped[str] = mapped_column(Text, nullable=False)
    is_ai_generated: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime, default=lambda: datetime.now(timezone.utc), nullable=False
    )

    # Relationships
    category: Mapped["Category"] = relationship("Category", back_populates="prompts")

    def __repr__(self) -> str:
        return f"<Prompt(id={self.id}, category_id={self.category_id}, is_ai={self.is_ai_generated})>"
